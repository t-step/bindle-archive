def _body(**overrides):
    body = {
        "schema_version": 1,
        "kind": "identity_allocation",
        "project_id": PROJECT_ID,
        "decided_at": "2026-07-20T12:00:00Z",
    }
    body.update(overrides)
    return body


def _alloc(arch_id, paths, symbols, neighborhood=None):
    payload = {"source_paths": list(paths), "symbol_names": list(symbols)}
    if neighborhood is not None:
        payload["neighborhood"] = list(neighborhood)
    return canonical.stamp(_body(
        kind="identity_allocation", arch_id=arch_id, payload=payload))


def _kind(arch_id, kind, payload=None, decided_at="2026-07-20T13:00:00Z"):
    body = _body(kind=kind, arch_id=arch_id, decided_at=decided_at)
    if payload is not None:
        body["payload"] = payload
    return canonical.stamp(body)


def _fold(*records):
    return judgments.fold_judgments(list(records))


ALPHA_ALLOC = _alloc(ALPHA, ALPHA_PATHS, ALPHA_SYMBOLS)
BETA_ALLOC = _alloc(BETA, BETA_PATHS, BETA_SYMBOLS)
# Gamma occupies alpha's exact territory — the corpus's contest fixture.
GAMMA_ALLOC = _alloc(GAMMA, ALPHA_PATHS, ALPHA_SYMBOLS)

TWO_LIVE = _fold(ALPHA_ALLOC, BETA_ALLOC)
EMPTY_AUTHORITY = _fold()


def _outcomes_by_key(result):
    return {o["candidate_key"]: o for o in result["outcomes"]}


class TestCandidateValidation(unittest.TestCase):
    """A malformed candidate is a HARD ABORT, not a dropped row: a candidate
    silently skipped is a node that never gets an identity, and the next run
    mints a duplicate for the same code."""

    def test_a_candidate_missing_a_required_field_aborts(self):
        for field in ("candidate_key", "projection_type", "source_paths",
                      "symbol_names"):
            with self.subTest(field=field):
                candidate = dict(CAND_ALPHA_EXACT)
                del candidate[field]
                with self.assertRaises(matcher.MatcherInputError) as caught:
                    matcher.match([candidate], TWO_LIVE)
                codes = [f["code"] for f in caught.exception.findings]
                self.assertIn("E_ARCH_CANDIDATE_MISSING_FIELD", codes)

    def test_an_unknown_candidate_field_aborts(self):
        candidate = dict(CAND_ALPHA_EXACT, provider_id="mcp://sym/42")
        with self.assertRaises(matcher.MatcherInputError) as caught:
            matcher.match([candidate], TWO_LIVE)
        codes = [f["code"] for f in caught.exception.findings]
        self.assertIn("E_ARCH_CANDIDATE_UNKNOWN_FIELD", codes)

    def test_an_unknown_projection_type_aborts(self):
        candidate = dict(CAND_ALPHA_EXACT, projection_type="arch_flow")
        with self.assertRaises(matcher.MatcherInputError) as caught:
            matcher.match([candidate], TWO_LIVE)
        codes = [f["code"] for f in caught.exception.findings]
        self.assertIn("E_ARCH_CANDIDATE_BAD_PROJECTION_TYPE", codes)

    def test_a_duplicate_candidate_key_aborts(self):
        with self.assertRaises(matcher.MatcherInputError) as caught:
            matcher.match([CAND_ALPHA_EXACT, dict(CAND_ALPHA_EXACT)], TWO_LIVE)
        codes = [f["code"] for f in caught.exception.findings]
        self.assertIn("E_ARCH_CANDIDATE_DUPLICATE_KEY", codes)

    def test_the_projection_types_accepted_are_the_frozen_ones(self):
        for projection_type in state.PROJECTION_TYPES:
            with self.subTest(projection_type=projection_type):
                candidate = dict(CAND_UNRELATED, projection_type=projection_type)
                matcher.match([candidate], TWO_LIVE)


class TestLivenessComesFromTheJudgmentsFold(unittest.TestCase):
    """#228 forbids recovering meaning from index.json, and projection_status
    lives there — so liveness is derived from the log's own decision records.
    This is the minimum lifecycle interpretation the frozen match-scoping
    rule forces on B; everything past it is child G's."""

    def test_an_allocated_identity_is_live(self):
        signals = matcher.identity_signals(TWO_LIVE)
        self.assertEqual(signals[ALPHA]["status"], "live")
        self.assertEqual(signals[BETA]["status"], "live")

    def test_a_stale_record_makes_an_identity_stale(self):
        fold = _fold(ALPHA_ALLOC, _kind(ALPHA, "stale"))
        self.assertEqual(matcher.identity_signals(fold)[ALPHA]["status"], "stale")
        self.assertNotIn(ALPHA, matcher.live_identities(fold))

    def test_a_reappearance_after_a_stale_revives_the_identity(self):
        fold = _fold(ALPHA_ALLOC,
                     _kind(ALPHA, "stale", decided_at="2026-07-20T13:00:00Z"),
                     _kind(ALPHA, "reappearance", decided_at="2026-07-20T14:00:00Z"))
        self.assertEqual(matcher.identity_signals(fold)[ALPHA]["status"], "live")

    def test_file_order_decides_liveness_not_decided_at(self):
        """decided_at is audit only — a synced notes home can carry clock
        skew, so a later-in-file stale wins over a later-timestamped revive."""
        fold = _fold(ALPHA_ALLOC,
                     _kind(ALPHA, "reappearance", decided_at="2026-07-20T23:00:00Z"),
                     _kind(ALPHA, "stale", decided_at="2026-07-20T09:00:00Z"))
        self.assertEqual(matcher.identity_signals(fold)[ALPHA]["status"], "stale")

    def test_an_operator_amendment_sets_status_only_when_it_says_so(self):
        revived = _fold(ALPHA_ALLOC, _kind(ALPHA, "stale"),
                        _kind(ALPHA, "operator_amendment", {"status": "live"}))
        self.assertEqual(matcher.identity_signals(revived)[ALPHA]["status"], "live")
        silent = _fold(ALPHA_ALLOC, _kind(ALPHA, "stale"),
                       _kind(ALPHA, "operator_amendment", {"note": "typo"}))
        self.assertEqual(matcher.identity_signals(silent)[ALPHA]["status"], "stale")

    def test_a_later_record_carrying_signals_supersedes_the_allocation(self):
        moved = _fold(ALPHA_ALLOC, _kind(ALPHA, "continuity", {
            "source_paths": ["bin/authn/session.py"],
            "symbol_names": ["SessionStore"]}))
        signals = matcher.identity_signals(moved)[ALPHA]
        self.assertEqual(signals["source_paths"], frozenset(["bin/authn/session.py"]))

    def test_a_record_without_signals_leaves_them_alone(self):
        fold = _fold(ALPHA_ALLOC, _kind(ALPHA, "naming", {"name": "Auth"}))
        signals = matcher.identity_signals(fold)[ALPHA]
        self.assertEqual(signals["source_paths"], frozenset(ALPHA_PATHS))


class TestScoring(unittest.TestCase):
    """Provider-independent signals only, combined into the normalized [0,1]
    score that config.thresholds already presupposes."""

    def test_identical_signals_score_one(self):
        result = matcher.match([CAND_ALPHA_EXACT], TWO_LIVE)
        self.assertEqual(_outcomes_by_key(result)["component:auth"]["score"], 1.0)

    def test_disjoint_signals_score_zero(self):
        result = matcher.match([CAND_UNRELATED], TWO_LIVE)
        self.assertEqual(_outcomes_by_key(result)["component:queue"]["score"], 0.0)

    def test_every_score_is_within_the_unit_interval(self):
        result = matcher.match(
            [CAND_ALPHA_EXACT, CAND_BETA_EXACT, CAND_WEAK, CAND_UNRELATED],
            TWO_LIVE)
        for outcome in result["outcomes"]:
            with self.subTest(candidate=outcome["candidate_key"]):
                self.assertGreaterEqual(outcome["score"], 0.0)
                self.assertLessEqual(outcome["score"], 1.0)

    def test_an_absent_neighborhood_signal_cannot_cap_the_score(self):
        """Neighborhood is carried opaquely and child C does not exist yet,
        so it is absent everywhere today. If its weight were simply lost, a
        byte-identical candidate would score below the high threshold and
        every ordinary edit would route to a child that is not built."""
        result = matcher.match([CAND_ALPHA_EXACT], TWO_LIVE)
        self.assertEqual(_outcomes_by_key(result)["component:auth"]["score"], 1.0)

    def test_the_neighborhood_signal_participates_when_present(self):
        fold = _fold(_alloc(ALPHA, ALPHA_PATHS, ALPHA_SYMBOLS,
                            neighborhood=["bin/auth", "bin/session"]))
        near = matcher.match([dict(CAND_ALPHA_EXACT,
                                   neighborhood=["bin/auth", "bin/session"])], fold)
        far = matcher.match([dict(CAND_ALPHA_EXACT,
                                  neighborhood=["bin/queue"])], fold)
        self.assertGreater(_outcomes_by_key(near)["component:auth"]["score"],
                           _outcomes_by_key(far)["component:auth"]["score"])

    def test_the_weights_are_module_constants_summing_to_one(self):
        self.assertAlmostEqual(sum(matcher.SIGNAL_WEIGHTS.values()), 1.0)
        self.assertEqual(set(matcher.SIGNAL_WEIGHTS),
                         {"source_paths", "symbol_names", "neighborhood"})


class TestTheFourOutcomes(unittest.TestCase):
    """Exactly four outcomes exist and every candidate reaches exactly one."""

    def test_an_empty_authority_mints(self):
        """This is what lets a fresh project with an empty judgments.jsonl
        produce anything at all."""
        result = matcher.match([CAND_ALPHA_EXACT], EMPTY_AUTHORITY)
        outcome = _outcomes_by_key(result)["component:auth"]
        self.assertEqual(outcome["outcome"], "mint")
        self.assertEqual(outcome["reason"], "empty_authority")
        self.assertIsNone(outcome["arch_id"])
        self.assertFalse(outcome["routes_to_g"])

    def test_no_live_identity_above_the_low_threshold_mints(self):
        result = matcher.match([CAND_UNRELATED], TWO_LIVE)
        outcome = _outcomes_by_key(result)["component:queue"]
        self.assertEqual(outcome["outcome"], "mint")
        self.assertEqual(outcome["reason"], "no_match")

    def test_a_unique_high_match_reuses(self):
        result = matcher.match([CAND_ALPHA_EXACT], TWO_LIVE)
        outcome = _outcomes_by_key(result)["component:auth"]
        self.assertEqual(outcome["outcome"], "reuse")
        self.assertEqual(outcome["arch_id"], ALPHA)
        self.assertEqual(outcome["confidence"], "high")
        self.assertFalse(outcome["routes_to_g"])

    def test_an_ordinary_edit_reuses_rather_than_minting(self):
        """Membership delta alone is frozen as never identity-churning."""
        result = matcher.match([CAND_ALPHA_DRIFTED], TWO_LIVE)
        outcome = _outcomes_by_key(result)["component:auth"]
        self.assertEqual(outcome["outcome"], "reuse")
        self.assertEqual(outcome["arch_id"], ALPHA)

    def test_two_candidates_claiming_one_identity_are_both_contested(self):
        """A many-to-one claim is a MERGE. Never resolve it by picking a
        winner — both are demoted to ambiguous and routed."""
        twin = dict(CAND_ALPHA_EXACT, candidate_key="component:auth-2")
        result = matcher.match([CAND_ALPHA_EXACT, twin], TWO_LIVE)
        outcomes = _outcomes_by_key(result)
        for key in ("component:auth", "component:auth-2"):
            with self.subTest(candidate=key):
                self.assertEqual(outcomes[key]["outcome"], "contested")
                self.assertEqual(outcomes[key]["confidence"], "medium")
                self.assertTrue(outcomes[key]["routes_to_g"])
                self.assertIsNone(outcomes[key]["arch_id"])
        self.assertEqual(outcomes["component:auth"]["contested_with"], [ALPHA])
        self.assertEqual(outcomes["component:auth"]["contested_by"],
                         ["component:auth-2"])

    def test_one_candidate_claiming_two_identities_is_contested(self):
        """A one-to-many claim is a SPLIT — same demotion, other direction."""
        fold = _fold(ALPHA_ALLOC, GAMMA_ALLOC)
        result = matcher.match([CAND_ALPHA_EXACT], fold)
        outcome = _outcomes_by_key(result)["component:auth"]
        self.assertEqual(outcome["outcome"], "contested")
        self.assertEqual(outcome["reason"], "contested_high")
        self.assertEqual(outcome["contested_with"], sorted([ALPHA, GAMMA]))

    def test_a_low_confidence_match_is_routed_never_silently_reused(self):
        result = matcher.match([CAND_WEAK], TWO_LIVE)
        outcome = _outcomes_by_key(result)["component:mixed"]
        self.assertEqual(outcome["outcome"], "routed")
        self.assertEqual(outcome["reason"], "low_confidence")
        self.assertEqual(outcome["confidence"], "medium")
        self.assertTrue(outcome["routes_to_g"])

    def test_a_reappearance_against_a_stale_identity_is_routed(self):
        """Unrelated code later written at the same paths would otherwise
        inherit the arch_id, prior_names, merged_from and every wikilink."""
        fold = _fold(ALPHA_ALLOC, _kind(ALPHA, "stale"))
        result = matcher.match([CAND_ALPHA_EXACT], fold)
        outcome = _outcomes_by_key(result)["component:auth"]
        self.assertEqual(outcome["outcome"], "routed")
        self.assertEqual(outcome["reason"], "stale_reappearance")
        self.assertEqual(outcome["arch_id"], ALPHA)
        self.assertTrue(outcome["routes_to_g"])

    def test_a_stale_identity_is_never_reused_and_never_contests_away(self):
        """The stale identity must not be quietly dropped from scoring
        either: dropping it turns a reappearance into a mint, which is a
        second identity for the same code."""
        fold = _fold(ALPHA_ALLOC, _kind(ALPHA, "stale"))
        result = matcher.match([CAND_ALPHA_EXACT], fold)
        outcome = _outcomes_by_key(result)["component:auth"]
        self.assertNotEqual(outcome["outcome"], "mint")
        self.assertNotEqual(outcome["outcome"], "reuse")

    def test_every_candidate_reaches_exactly_one_outcome(self):
        candidates = [CAND_ALPHA_EXACT, CAND_BETA_EXACT, CAND_WEAK,
                      CAND_UNRELATED]
        result = matcher.match(candidates, TWO_LIVE)
        self.assertEqual(len(result["outcomes"]), len(candidates))
        self.assertEqual(sorted(o["candidate_key"] for o in result["outcomes"]),
                         sorted(c["candidate_key"] for c in candidates))
        for outcome in result["outcomes"]:
            with self.subTest(candidate=outcome["candidate_key"]):
                self.assertIn(outcome["outcome"], matcher.OUTCOMES)

    def test_the_outcome_vocabulary_is_the_frozen_four(self):
        self.assertEqual(matcher.OUTCOMES,
                         ("mint", "reuse", "contested", "routed"))

    def test_a_recorded_confidence_is_always_a_frozen_band(self):
        result = matcher.match(
            [CAND_ALPHA_EXACT, CAND_WEAK, CAND_UNRELATED], TWO_LIVE)
        for outcome in result["outcomes"]:
            with self.subTest(candidate=outcome["candidate_key"]):
                if outcome["confidence"] is not None:
                    self.assertIn(outcome["confidence"], state.CONFIDENCE_VALUES)

    def test_medium_is_never_collapsed_into_a_silent_reuse(self):
        """B may not collapse the medium band into reuse — every medium
        outcome routes."""
        fold = _fold(ALPHA_ALLOC, GAMMA_ALLOC)
        result = matcher.match([CAND_ALPHA_EXACT, CAND_WEAK], fold)
        for outcome in result["outcomes"]:
            if outcome["confidence"] == "medium":
                with self.subTest(candidate=outcome["candidate_key"]):
                    self.assertTrue(outcome["routes_to_g"])
                    self.assertNotEqual(outcome["outcome"], "reuse")


class TestThresholds(unittest.TestCase):
    """config.thresholds has been required since slice 2 with no consumer.
    This is the consumer."""

    def test_the_defaults_satisfy_the_frozen_config_constraint(self):
        self.assertLess(matcher.DEFAULT_THRESHOLDS["low"],
                        matcher.DEFAULT_THRESHOLDS["high"])
        for value in matcher.DEFAULT_THRESHOLDS.values():
            self.assertGreaterEqual(value, 0.0)
            self.assertLessEqual(value, 1.0)

    def test_a_config_threshold_pair_is_honored(self):
        """Raising high above a candidate's score turns a reuse into a
        routed low-confidence match — the operator knob actually moves."""
        strict = matcher.match([CAND_ALPHA_DRIFTED], TWO_LIVE,
                               thresholds={"high": 0.99, "low": 0.1})
        self.assertEqual(_outcomes_by_key(strict)["component:auth"]["outcome"],
                         "routed")
        loose = matcher.match([CAND_ALPHA_DRIFTED], TWO_LIVE,
                              thresholds={"high": 0.5, "low": 0.1})
        self.assertEqual(_outcomes_by_key(loose)["component:auth"]["outcome"],
                         "reuse")

    def test_raising_low_turns_a_routed_match_into_a_mint(self):
        result = matcher.match([CAND_WEAK], TWO_LIVE,
                               thresholds={"high": 0.9, "low": 0.85})
        self.assertEqual(_outcomes_by_key(result)["component:mixed"]["outcome"],
                         "mint")

    def test_thresholds_violating_the_frozen_ordering_abort(self):
        with self.assertRaises(matcher.MatcherInputError):
            matcher.match([CAND_ALPHA_EXACT], TWO_LIVE,
                          thresholds={"high": 0.4, "low": 0.8})


class TestDeterminism(unittest.TestCase):
    """FC-8: the same inputs produce the same outcomes, every run."""

    def test_outcomes_are_ordered_by_candidate_key(self):
        result = matcher.match(
            [CAND_UNRELATED, CAND_ALPHA_EXACT, CAND_BETA_EXACT], TWO_LIVE)
        keys = [o["candidate_key"] for o in result["outcomes"]]
        self.assertEqual(keys, sorted(keys))

    def test_input_order_does_not_change_the_result(self):
        forward = matcher.match(
            [CAND_ALPHA_EXACT, CAND_BETA_EXACT, CAND_WEAK], TWO_LIVE)
        backward = matcher.match(
            [CAND_WEAK, CAND_BETA_EXACT, CAND_ALPHA_EXACT], TWO_LIVE)
        self.assertEqual(forward, backward)

    def test_an_equal_scoring_pair_breaks_the_tie_by_arch_id(self):
        """Two identities tied BELOW the high threshold — above it they
        would be a contest, which names no winner at all. The reported
        best match must not depend on mapping iteration order."""
        fold = _fold(_alloc(BETA, ALPHA_PATHS, ALPHA_SYMBOLS),
                     _alloc(ALPHA, ALPHA_PATHS, ALPHA_SYMBOLS))
        result = matcher.match([CAND_WEAK], fold,
                               thresholds={"high": 0.99, "low": 0.01})
        outcome = _outcomes_by_key(result)["component:mixed"]
        self.assertEqual(outcome["outcome"], "routed")
        self.assertEqual(outcome["arch_id"], min(ALPHA, BETA))

    def test_repeated_runs_are_identical(self):
        candidates = [CAND_ALPHA_EXACT, CAND_WEAK, CAND_UNRELATED]
        first = matcher.match(candidates, TWO_LIVE)
        second = matcher.match(candidates, TWO_LIVE)
        self.assertEqual(first, second)


class TestTheMatcherWritesNothing(unittest.TestCase):
    """The matcher runs during PREVIEW, before any confirmation. Minting is
    D's confirmed-creation-event call to judgments.commit_identity_then; a
    matcher that minted would allocate an identity nobody confirmed, and the
    frozen ordering makes that append irreversible.

    Slice 2's equivalent guard covers state.py by name only, so a new module
    needs its own or the package's purity silently stops being asserted."""

    def test_the_module_contains_no_write_operation(self):
        source_path = os.path.join(os.path.dirname(__file__), "..", "matcher.py")
        with open(source_path, "r", encoding="utf-8") as handle:
            source = handle.read()
        for forbidden in ("open(", "makedirs", "write_atomic",
                          "append_line_atomic", "os.replace", "append_judgment",
                          "commit_identity_then"):
            with self.subTest(forbidden=forbidden):
                self.assertNotIn(forbidden, source)

    def test_the_module_never_reads_index_json(self):
        """index.json is durable projection state and is NEVER an authority
        for meaning — the matcher's identities come from the log."""
        source_path = os.path.join(os.path.dirname(__file__), "..", "matcher.py")
        with open(source_path, "r", encoding="utf-8") as handle:
            source = handle.read()
        for forbidden in ("index_path", "INDEX_FILENAME", "projection_status"):
            with self.subTest(forbidden=forbidden):
                self.assertNotIn(forbidden, source)

    def test_matching_leaves_the_fold_unmutated(self):
        fold = _fold(ALPHA_ALLOC, BETA_ALLOC)
        before = repr(fold)
        matcher.match([CAND_ALPHA_EXACT, CAND_WEAK], fold)
        self.assertEqual(repr(fold), before)

    def test_matching_leaves_the_candidates_unmutated(self):
        candidate = dict(CAND_ALPHA_EXACT)
        before = repr(candidate)
        matcher.match([candidate], TWO_LIVE)
        self.assertEqual(repr(candidate), before)


class TestProviderIndependence(unittest.TestCase):
    """Raw provider IDs change format across provider versions; scoring on
    one would route every node to G on a patch bump."""

    def test_the_candidate_shape_has_no_provider_field(self):
        self.assertEqual(matcher.CANDIDATE_REQUIRED,
                         ("candidate_key", "projection_type", "source_paths",
                          "symbol_names"))
        self.assertEqual(matcher.CANDIDATE_KNOWN,
                         frozenset(matcher.CANDIDATE_REQUIRED + ("neighborhood",)))

    def test_a_provider_id_cannot_be_smuggled_in_as_a_signal(self):
        candidate = dict(CAND_ALPHA_EXACT, provider_version="2.0.0")
        with self.assertRaises(matcher.MatcherInputError):
            matcher.match([candidate], TWO_LIVE)


