"""The confidence-gated continuity matcher (#228, epic #141).

The frozen contract this exercises: matching is a BIPARTITE ASSIGNMENT
between this run's candidates and the LIVE confirmed identities, scored on
PROVIDER-INDEPENDENT signals, with FOUR EXHAUSTIVE OUTCOMES — no-match ->
mint, unique-high -> reuse, contested-high -> demote all to ambiguous -> G,
low/ambiguous -> G. A structural match against a STALE identity is a
reappearance and is routed, never auto-reused.

The synthetic corpus below is written as LITERAL data — candidate dicts and
judgment records spelled out by hand — deliberately not generated by any
helper the matcher itself uses. A corpus, a validator, and a writer that all
route through one implementation prove agreement, not correctness.
"""
import os
import sys
import unittest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", ".."))

from architecture import canonical
from architecture import judgments
from architecture import matcher
from architecture import state

