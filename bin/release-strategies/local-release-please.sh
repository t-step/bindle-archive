#!/usr/bin/env bash
#
# local-release-please.sh — the local Release Please ARTIFACT strategy for
# Release Captain (L4 of #116). Release Please is the artifact authority: it
# owns the VERSION bump, the CHANGELOG.md content, and the release PR. This
# strategy assembles the `release-please release-pr` invocation and, on
# `apply`, chains `release-please-sync.sh apply` onto the same release PR
# branch (issue #152) — Release Please's own `extra-files` mechanism cannot
# update Bindle's bare, unannotated `VERSION` file, so without this chain the
# release PR is created with `VERSION` still disagreeing with the manifest
# until someone remembers the separate sync step. This strategy NEVER merges,
# tags, creates a GitHub Release, publishes, or deploys — publication is a
# separate, explicitly human-authorized action.
#
# Verbs:
#   dry-run  read-only preview; proves zero mutation.
#   apply    create/update the release PR, then sync VERSION onto it;
#            requires --approval-token <token>, supplied verbatim by the human
#            operator (never generated by the orchestrator itself) for this
#            one invocation (reused for the chained sync — one grant covers
#            both, since together they leave the release PR in one consistent
#            state). No token => hard stop, no invocation. The token is
#            ephemeral invocation state, never a reusable secret or a
#            persisted approval marker.
#
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
: "${RELEASE_PLEASE_SYNC_CMD:=$REPO_ROOT/bin/release-please-sync.sh}"

verb="${1:-}"
shift || true

: "${RELEASE_PLEASE_CMD:=npx release-please}"
repo_url="${RELEASE_PLEASE_REPO_URL:-}"
if [ -z "$repo_url" ]; then
  origin="$(git remote get-url origin 2>/dev/null || true)"
  # normalize git@github.com:o/r.git and https://github.com/o/r(.git) -> o/r
  repo_url="$(printf '%s' "$origin" | sed -E 's#^git@[^:]+:##; s#^https?://[^/]+/##; s#\.git$##')"
fi

rp() { # invoke the (possibly stubbed) release-please binary with args
  # shellcheck disable=SC2086 # RELEASE_PLEASE_CMD may be "npx release-please"
  $RELEASE_PLEASE_CMD "$@"
}

# Resolve a GitHub token for release-please (its CLI requires --token; it does
# not read GITHUB_TOKEN on its own). Prefer $GITHUB_TOKEN, fall back to the
# local gh CLI. Echoes the token (possibly empty); the caller enforces presence
# in the main shell so `exit` is not swallowed by a command-substitution subshell.
resolve_gh_token() {
  local t="${GITHUB_TOKEN:-}"
  if [ -z "$t" ] && command -v gh >/dev/null 2>&1; then
    t="$(gh auth token 2>/dev/null || true)"
  fi
  printf '%s' "$t"
}

# Enforce token presence in the MAIN shell (not a $()-subshell, so exit 4 is
# not swallowed). Sets $gh_tok on success; exits 4 with a clear message if none.
no_token_msg="local-release-please: no GitHub token (set GITHUB_TOKEN or run 'gh auth login')"

case "$verb" in
  dry-run)
    gh_tok="$(resolve_gh_token)"
    [ -n "$gh_tok" ] || {
      echo "$no_token_msg" >&2
      exit 4
    }
    rp release-pr --repo-url="$repo_url" --token="$gh_tok" --dry-run "$@"
    ;;
  apply)
    token=""
    while [ "$#" -gt 0 ]; do
      case "$1" in
        --approval-token)
          token="${2:-}"
          shift 2
          ;;
        --approval-token=*)
          token="${1#*=}"
          shift
          ;;
        *) shift ;;
      esac
    done
    if [ -z "$token" ]; then
      echo "local-release-please: apply refused — no approval token" >&2
      exit 3
    fi
    gh_tok="$(resolve_gh_token)"
    [ -n "$gh_tok" ] || {
      echo "$no_token_msg" >&2
      exit 4
    }
    rp release-pr --repo-url="$repo_url" --token="$gh_tok"
    "$RELEASE_PLEASE_SYNC_CMD" apply --approval-token "$token"
    ;;
  *)
    echo "local-release-please: unknown verb '${verb:-<none>}'" >&2
    exit 2
    ;;
esac
