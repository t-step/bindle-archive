#!/usr/bin/env bash
#
# release-please-sync.sh — syncs Bindle's bare VERSION file onto the open
# Release Please release-PR branch (issue #137).
#
# release-please-config.json used to list VERSION under extra-files, but
# Release Please's generic file updater only rewrites lines carrying an
# x-release-please-version annotation comment — Bindle's bare VERSION has
# none, so that entry was a silent no-op (removed; see release-please-config.json).
# This script closes the gap: it reads the version Release Please already
# computed (from the release PR branch's .release-please-manifest.json) and
# writes it into VERSION, in one follow-up commit pushed onto the SAME PR
# branch. It never creates a new PR, never touches main, never tags, merges,
# or publishes.
#
# Run from inside the target repo's working tree — same convention as
# bin/release-strategy.sh and bin/release-strategies/local-release-please.sh
# (no chdir to a fixed location; operates on the caller's cwd via `git -C`).
#
# Usage:
#   bin/release-please-sync.sh dry-run [--pr <N>]
#   bin/release-please-sync.sh check [--pr <N>]
#   bin/release-please-sync.sh apply --approval-token <token> [--pr <N>]
#
# `--pr <N>` (issue #438) names the release PR directly and skips the
# `autorelease: pending` label search. The chained path in
# bin/release-strategies/local-release-please.sh runs this script immediately
# after `release-please release-pr`, and the label is often not yet visible to
# the search at that moment — a race that failed the v0.7.0 and v0.10.1 cuts.
# release-please's own output already names the PR, so the strategy passes it
# through. The label search remains the default for standalone operator runs,
# where no PR number is at hand.
#
# `check` (issue #265) is the deterministic gate: read-only, no token, exit 12
# when the release PR's VERSION and .release-please-manifest.json disagree. The
# v0.7.0 cut shipped that state because the chained sync ran before the PR was
# labeled, reported "nothing to sync", and exited without anyone verifying the
# result. The release strategy now runs `check` after the sync, so that outcome
# fails the release flow instead of resting on a hand-remembered follow-up.
# Exit codes are distinguishable on purpose: 10 no release PR, 11 ambiguous,
# 12 mismatch, 13 forward-merge conflict — an unrun check is never reported as
# a passing one.
#
# `apply` also merges the base branch forward when the release PR's branch is
# behind it (issue #415): `release-please release-pr` leaves the branch's base
# pinned whenever its own computed diff is unchanged, so a fix merged to the
# target branch between PR creation and apply never reaches the release branch
# — and the gates below then re-fail against stale content no matter how many
# times the target branch is fixed (how the v0.10.0 cut got stuck). A
# conflicting forward-merge stops at exit 13 for manual resolution.
#
# --approval-token must be supplied verbatim by the human operator, never
# generated by the orchestrator itself — see skills/release-captain/SKILL.md.
#
set -euo pipefail

die() {
  echo "release-please-sync: $1" >&2
  exit "${2:-1}"
}

verb="${1:-}"
shift || true

token=""
pr_arg=""
while [ "$#" -gt 0 ]; do
  case "$1" in
    --approval-token)
      token="${2:-}"
      shift 2
      ;;
    --approval-token=*)
      token="${1#*=}"
      shift
      ;;
    --pr)
      pr_arg="${2:-}"
      shift 2
      ;;
    --pr=*)
      pr_arg="${1#*=}"
      shift
      ;;
    *) shift ;;
  esac
done

case "$verb" in
  dry-run | check) ;;
  apply)
    [ -n "$token" ] || die "apply refused — no approval token" 3
    ;;
  *)
    die "unknown verb '${verb:-<none>}' (want: dry-run|check|apply)" 2
    ;;
esac

if [ -n "$pr_arg" ] && ! printf '%s' "$pr_arg" | grep -Eq '^[0-9]+$'; then
  die "--pr wants a PR number, got '$pr_arg'" 2
fi

command -v gh >/dev/null 2>&1 || die "gh CLI not found on PATH" 4

repo_root="$(git rev-parse --show-toplevel)"

# --- find the release PR ----------------------------------------------------
if [ -n "$pr_arg" ]; then
  # #438: the caller already knows the PR — look it up directly instead of
  # racing the label search. Fail closed (10) on an unresolvable or non-open
  # PR; never silently fall back to guessing.
  pr_json="$(gh pr view "$pr_arg" --json number,headRefName,baseRefName,state 2>/dev/null)" ||
    die "gh could not resolve --pr $pr_arg to a pull request" 10
  pr_field() { printf '%s' "$pr_json" | python3 -c "import json,sys; print(json.load(sys.stdin)[\"$1\"])"; }
  pr_state="$(pr_field state)"
  [ "$pr_state" = "OPEN" ] || die "PR #$pr_arg is $pr_state, not open — refusing to treat it as the release PR" 10
else
  prs_json="$(gh pr list --state open --label "autorelease: pending" \
    --json number,headRefName,baseRefName)"
  pr_count="$(printf '%s' "$prs_json" | python3 -c 'import json,sys; print(len(json.load(sys.stdin)))')"
  [ "$pr_count" -ne 0 ] || die "no open PR labeled 'autorelease: pending' — nothing to sync" 10
  [ "$pr_count" -eq 1 ] || die "found $pr_count PRs labeled 'autorelease: pending' — expected exactly 1, refusing to guess" 11
  pr_field() { printf '%s' "$prs_json" | python3 -c "import json,sys; print(json.load(sys.stdin)[0][\"$1\"])"; }
fi
pr_number="$(pr_field number)"
head_ref="$(pr_field headRefName)"
base_ref="$(pr_field baseRefName)"

git -C "$repo_root" fetch -q origin "$head_ref" "$base_ref"

manifest_version() { # manifest_version <ref>
  git -C "$repo_root" show "$1:.release-please-manifest.json" |
    python3 -c 'import json,sys; print(json.load(sys.stdin)["."])'
}

new_version="$(manifest_version "origin/$head_ref")"
branch_version="$(git -C "$repo_root" show "origin/$head_ref:VERSION")"

in_sync=0
if [ "$branch_version" = "$new_version" ]; then
  in_sync=1
fi

# #415: is the release branch's base pinned behind the target branch?
behind=0
git -C "$repo_root" merge-base --is-ancestor "origin/$base_ref" "origin/$head_ref" || behind=1

# `check` is the gate (#265): a release PR carrying a bumped manifest and a
# stale VERSION is not a releasable PR, and saying so must not depend on a
# human remembering to look. Exit 12 is distinct from "no PR" (10) and
# "ambiguous" (11) so a caller can tell a mismatch from an unrun check. It
# certifies VERSION↔manifest agreement and nothing else — behind-ness is
# apply's job (#415), not a release-blocker by itself.
if [ "$verb" = "check" ]; then
  if [ "$in_sync" -eq 1 ]; then
    echo "release-please-sync: VERSION already in sync at $new_version (PR #$pr_number, $head_ref)"
    exit 0
  fi
  die "release PR #$pr_number ($head_ref) is inconsistent: VERSION $branch_version, manifest $new_version — run bin/release-please-sync.sh apply --approval-token <token>" 12
fi

if [ "$in_sync" -eq 1 ] && [ "$behind" -eq 0 ]; then
  echo "release-please-sync: VERSION already in sync at $new_version (PR #$pr_number, $head_ref)"
  exit 0
fi

if [ "$in_sync" -eq 0 ]; then
  echo "release-please-sync: PR #$pr_number ($head_ref) — VERSION $branch_version -> $new_version"
fi
if [ "$behind" -eq 1 ]; then
  echo "release-please-sync: PR #$pr_number ($head_ref) is behind origin/$base_ref — release-please pins the branch base when its own diff is unchanged (#415)"
fi

if [ "$verb" = "dry-run" ]; then
  if [ "$behind" -eq 1 ]; then
    echo "release-please-sync: dry-run — would merge origin/$base_ref forward on $head_ref"
  fi
  if [ "$in_sync" -eq 0 ]; then
    echo "release-please-sync: dry-run — would sync VERSION on $head_ref"
  fi
  exit 0
fi

# --- apply: sync onto the PR branch in an isolated worktree -----------------
wt_dir="$repo_root/.worktrees/release-please-sync"
wt_branch="_release-please-sync"

git -C "$repo_root" worktree remove --force "$wt_dir" >/dev/null 2>&1 || true
git -C "$repo_root" worktree prune >/dev/null 2>&1 || true
rm -rf "$wt_dir"

cleanup() {
  git -C "$repo_root" worktree remove --force "$wt_dir" >/dev/null 2>&1 || true
  git -C "$repo_root" branch -D "$wt_branch" >/dev/null 2>&1 || true
}
trap cleanup EXIT

git -C "$repo_root" worktree add -q -B "$wt_branch" "$wt_dir" "origin/$head_ref"

(
  cd "$wt_dir"
  # Forward-merge FIRST (#415), so the gates below run against the release
  # branch as it will actually merge — not against its pinned, stale base.
  if [ "$behind" -eq 1 ]; then
    if ! git merge -q -m "chore: merge $base_ref forward into $head_ref (#415)" "origin/$base_ref"; then
      echo "release-please-sync: merging origin/$base_ref into $head_ref hit conflicts — resolve them on $head_ref manually, push, then re-run apply" >&2
      exit 13
    fi
  fi
  if [ "$in_sync" -eq 0 ]; then
    printf '%s\n' "$new_version" >VERSION
  fi
  bin/check.sh
  bin/test-install.sh
  if [ "$in_sync" -eq 0 ]; then
    git add VERSION
    git commit -q -m "chore: sync VERSION to v${new_version}"
  fi
  git push -q origin "HEAD:$head_ref"
)

if [ "$behind" -eq 1 ] && [ "$in_sync" -eq 0 ]; then
  echo "release-please-sync: merged $base_ref forward and pushed VERSION sync onto $head_ref (PR #$pr_number)"
elif [ "$behind" -eq 1 ]; then
  echo "release-please-sync: merged $base_ref forward onto $head_ref (PR #$pr_number)"
else
  echo "release-please-sync: pushed VERSION sync onto $head_ref (PR #$pr_number)"
fi
